function ns.SynchronizeActiveLocale()
    local clientLoc = (GetLocale and GetLocale()) or "enUS"
    if clientLoc == "esMX" then clientLoc = "esES" elseif clientLoc == "enGB" then clientLoc = "enUS" end
    local userPref = (ns.DB and ns.DB.lang) or "auto"
    if userPref ~= "auto" and LOCALES[userPref] then
        ns.activeLocale = userPref
    else
        ns.activeLocale = LOCALES[clientLoc] and clientLoc or "enUS"
    end
    ns.L_ACTIVE = LOCALES[ns.activeLocale] or L_EN
    -- names of this language from EzWoW - Data, when its built-in table was dropped (Core/SharedData.lua)
    if ns.SharedData and ns.SharedData.UseLocale then pcall(ns.SharedData.UseLocale, ns.activeLocale) end
end

ns.SynchronizeActiveLocale()

ns.L = setmetatable({}, {
    __index = function(_, k)
        local active = ns.L_ACTIVE or L_EN
        return active[k] or L_EN[k]
    end,
})

